# Localizando Elementos na Tupla

"""
Dada a tupla valores = (10, 50, 20, 50, 30, 50, 40), 
faça o seguinte:

Use o método .count() para mostrar quantas vezes 
o número 50 aparece.

Use o método .index() para encontrar em qual 
posição (índice) está o número 30.

Use a função len() para exibir o tamanho total da tupla.
"""

valores =  (10, 50, 20, 50, 30, 50, 40)

print(valores.count(50))
print(valores.index(30))
print(len(valores))