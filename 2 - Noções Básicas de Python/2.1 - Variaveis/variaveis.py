# Variáveis

# Declaração e atribuição de variáveis

"""
As variáveis são contêineres que nos permitem armazenar
e manipular dados em nossos programas. 
Para declarar e atribuir um valor a uma variável em Python 
utilizamos o operador de atribuição =.
O nome da variável vai à esquerda do operador, 
e o valor que você deseja atribuir vai à direita. 
Por exemplo:
"""

nome = "Juan"
idade = 25
altura = 1.75
é_estudante = True

"""
No exemplo, declaramos e atribuímos valores às variáveis
nome, idade, altura e é_estudante. 
O Python infere automaticamente o tipo de dados
de cada variável 
com base no valor atribuído.


Você também pode atribuir o mesmo valor 
a várias variáveis em 
uma única linha usando o operador de atribuição múltipla:
"""
a = b = c = 10

"""
Neste caso, as variáveis a, b e c terão o valor 10.
"""