# Inteiros (int)

"""
Os números inteiros são aqueles que não têm parte decimal. 
Em Python, são representados simplesmente escrevendo o 
número sem aspas nem pontos decimais. Por exemplo:
"""

idade = 20
quantidade = 100



# Flutuantes (float)

"""
Os números flutuantes, também conhecidos como números de 
ponto flutuante, são aqueles que têm uma parte decimal.
Em Python, são representados utilizando 
um ponto para separar a parte inteira da parte decimal. 
Por exemplo:
"""

preço = 9.99
altura = 1.75



# Cadeias de texto (strings)

"""
As cadeias de texto, ou simplesmente cadeias, 
são sequências de caracteres 
encerradas entre aspas simples ('...') ou duplas ("..."). 
São utilizadas para representar texto em Python. 
Por exemplo:
"""

nome = "Juan"
mensagem = '¡Hola, mundo!'




# Booleanos (bool)
"""
Os valores booleanos são aqueles que representam
verdadeiro ou falso. 
Em Python, são representados pelos literais True e False. 
Os valores booleanos em Python começam com uma 
letra maiúscula: 
True e False.
Por exemplo:
"""

é_maior_de_idade = True
tem_desconto = False

